### بررسی خطای زیرساخت توسط مسئول انتشار

اگر API آمادهٔ دریافت درخواست نیست، مسئول انتشار `/health/ready` را بررسی می‌کند؛ پاسخ ۵۰۳ و statusهای database، migrations و adminAuthentication مسیر اصلاح تنظیمات یا اتصال را مشخص می‌کنند. هنگام قطع دیتابیس، سالم‌بودن `/health/live` به معنی آماده‌بودن عملیات فروش نیست. جزئیات و راه بازیابی در `docs/API_READINESS.md` آمده است.


### مسیرهای سریع متناسب با نقش (#92)

مسیر ورود: داشبورد ← «امروز چه کاری انجام دهید؟» ← بخش مجاز. هدف این بخش انتخاب عملیات روزانه با دسترسی واقعی نشست است؛ فیلتر مجوز توسط سرور همچنان مرجع نهایی است. کاربر فقط‌خواندنی پیشنهاد ثبت یا اصلاح نمی‌بیند. اگر هیچ مسیر عملیاتی برای نقش فعال نباشد، راهنمای هماهنگی با مدیر فروشگاه نمایش داده می‌شود. کارت فقط صفحهٔ مقصد را باز می‌کند و داده‌ای را ذخیره نمی‌کند؛ بازگشت از منوی «داشبورد» انجام می‌شود. این مسیرها به محصول، موجودی، سفارش و فروش سازمانی متصل‌اند؛ هیچ محاسبهٔ مالی در کلاینت اضافه نشده است.

### پیگیری خطا با شناسهٔ درخواست

برای خطای قابل تکرار، مسئول فنی شناسهٔ `X-Request-ID` پاسخ API یا `requestId` در پیام استاندارد خطا را با لاگ سرور تطبیق می‌دهد. اصلاح موجودی، انتشار محصول و تغییر کاربران همین شناسه را در Audit ثبت می‌کنند. فقط شناسه را برای پیگیری ارسال کنید؛ رمز، token، اطلاعات مشتری و بدنهٔ فرم لازم نیست. مسیر عملیاتی و قرارداد در `docs/API_OBSERVABILITY.md` آمده است.


### اعلان‌های متناسب با مجوز

مجوز ورود به داشبورد به‌تنهایی مجوز دیدن هشدارهای سفارش یا انبار نیست. سرور فقط اعلان‌های حوزه‌هایی را می‌فرستد که نقش شما اجازهٔ مشاهده‌شان را دارد. عدد صفر در حوزهٔ نامجاز، آمار واقعی آن حوزه را نشان نمی‌دهد؛ برای دسترسی با مدیر فروشگاه هماهنگ کنید. قرارداد نقش‌ها و تست امنیتی در `docs/NOTIFICATION_PERMISSIONS.md` آمده است.


