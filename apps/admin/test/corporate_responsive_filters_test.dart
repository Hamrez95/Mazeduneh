## حالت‌های استاندارد صفحه

- Loading: ساختار صفحه و progress قابل فهم.
- Empty: توضیح اینکه چرا خالی است، اقدام اصلی و link راهنما.
- Error: علت ساده، retry امن و مسیر تماس.
- Forbidden: توضیح permission بدون افشای اطلاعات حساس.
- Success: نتیجه، toast/inline status و next action.
- Stale: زمان آخرین به‌روزرسانی، refresh و هشدار اینکه داده ممکن است قدیمی باشد.

